axes[0].plot(est_xy[:, 0],  est_xy[:, 1],  'r--', lw=0.8, label='EKF estimate')
for i, b in enumerate(beacons):
    axes[0].plot(b[0], b[1], 'gx', ms=12, mew=3, label=f'Beacon {i+1}' if i == 0 else '')
axes[0].set_aspect('equal')
axes[0].set_xlabel('x (m)')
axes[0].set_ylabel('y (m)')
axes[0].legend(fontsize=8)
axes[0].set_title('Vehicle trajectory')

# --- Lateral offset ---
t_ax = np.arange(n_steps) * h
axes[1].plot(t_ax,      log_true[:, 1], 'b-',  lw=0.9, label=r'True $\ell_t$')
axes[1].plot(t_ax[:-1], log_est[:,  1], 'r--', lw=0.9, label=r'EKF $\hat{\ell}_{t|t}$')
axes[1].axhline( 2.0, color='k', ls=':', lw=1.0, label='Boundary ±2 m')
axes[1].axhline(-2.0, color='k', ls=':', lw=1.0)
