axes[1].set_ylabel('Lateral offset (m)')
axes[1].legend(fontsize=8)
axes[1].set_title('Lateral position')

# --- Longitudinal velocity ---
axes[2].plot(t_ax,      log_true[:, 2], 'b-',  lw=0.9, label=r'True $v_{s,t}$')
axes[2].plot(t_ax[:-1], log_est[:,  2], 'r--', lw=0.9, label=r'EKF $\hat{v}_{s,t|t}$')
axes[2].axhline(25.0, color='orange', ls='--', lw=1.0, label='Max speed (25 m/s)')
axes[2].set_xlabel('Time (s)')
axes[2].set_ylabel('Longitudinal velocity (m/s)')
axes[2].legend(fontsize=8)
axes[2].set_title('Velocity tracking')

plt.tight_layout()
plt.savefig('step3_ekf_results.png', dpi=150)
plt.show()

# --- Performance metrics ---
arc_err  = np.abs(log_true[:-1, 0] - log_est[:, 0])
lat_err  = np.abs(log_true[:-1, 1] - log_est[:, 1])

